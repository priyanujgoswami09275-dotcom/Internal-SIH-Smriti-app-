  static String forLanguage(String languageCode, String key) {
    final normalized = _normalize(languageCode);
    final resolvedKey = _keyAliases[key] ?? key;
    final languageStrings = _strings[normalized] ?? _strings['en']!;
    return languageStrings[resolvedKey] ?? _strings['en']![resolvedKey] ?? key;
  }

  static String text(BuildContext context, String key) => of(context).tr(key);

  static PatientLocalizations of(BuildContext context) =>
      Localizations.of<PatientLocalizations>(context, PatientLocalizations) ??
      PatientLocalizations(const Locale('en'));

  static Locale localeFor(String? languageCode) {
    final normalized = _normalize(languageCode ?? 'english');
    return Locale(_localeCodes[normalized]!);
  }

  static bool isLocalized(String languageCode) => const {
        'en',
        'english',
        'as',
        'assamese',
        'bn',
        'bengali',
        'hi',
        'hindi',
      }.contains(languageCode.toLowerCase());

  String tr(String key) => forLanguage(locale.languageCode, key);

