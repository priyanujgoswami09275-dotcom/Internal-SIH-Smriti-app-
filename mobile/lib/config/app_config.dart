/// App-wide configuration for the patient mobile app.
///
/// The backend base URL is supplied at build time and is REQUIRED for release
/// builds, so a shipped APK/AAB can never silently point at a developer machine:
///
///   flutter run --dart-define=API_BASE_URL=https://api.example.org
///   flutter build apk --release --dart-define=API_BASE_URL=https://api.example.org
///
/// Development presets (only used when the define is absent in a debug build):
///   - Android emulator:  http://10.0.2.2:8000  (host loopback)
///   - iOS simulator / desktop: http://localhost:8000
///   - Physical device on the same LAN: http://<LAN-IP>:8000
///
/// Demo-day tunnels (ngrok/Cloudflare) are temporary. Pass the current URL at
/// build time; do not edit this file to hardcode one.
library;

import 'package:flutter/foundation.dart';

/// True in a release/profile build. Debug builds keep the localhost defaults
/// so `flutter run` works with no flags.
const bool isReleaseBuild = bool.fromEnvironment('dart.vm.product');
const String _definedApiBaseUrl = String.fromEnvironment('API_BASE_URL');

/// Compile-time tripwire.
///
/// A release APK/AAB built without `API_BASE_URL` must not compile, so an app
/// that cannot reach any real backend can never be shipped. `assert` in a
/// `const` initializer is evaluated during compilation; debug/JIT builds are
/// unaffected.
class ReleaseApiUrlGuard {
  const ReleaseApiUrlGuard._()
      : assert(
          !isReleaseBuild || _definedApiBaseUrl.length > 0,
          'API_BASE_URL must be provided for a release build. Rebuild with '
          '--dart-define=API_BASE_URL=https://<your-api-host>.',
        );
  static const ReleaseApiUrlGuard instance = ReleaseApiUrlGuard._();
}

class AppConfig {
  AppConfig._();

  static const String _defined = _definedApiBaseUrl;

  static const String _devDefault = 'http://localhost:8000';
  static const String _androidEmulatorDefault = 'http://10.0.2.2:8000';

  /// Resolved API base URL for the current build.
  static String get apiBaseUrl {
    // Touching the guard here instantiates it during compilation, so an unset
    // release define fails the build rather than the first request.
    assert(ReleaseApiUrlGuard.instance == ReleaseApiUrlGuard.instance);
    return resolveApiBaseUrl(
      configured: _defined,
      release: isReleaseBuild,
      developmentDefault: _devDefaultForPlatform,
    );
  }

  static String get _devDefaultForPlatform {
    if (kIsWeb) return _devDefault;
    if (defaultTargetPlatform == TargetPlatform.android) {
      return _androidEmulatorDefault;
    }
    return _devDefault;
  }

  static const String apiV1 = '/api/v1';
}

/// Validates and normalizes an API base URL.
///
/// [release] switches on the guarantees a shipped binary must satisfy: an
/// explicit URL, HTTPS, and a public host. A release build throws
/// [StateError] rather than falling back, because an app that silently targets
/// `localhost` cannot reach real data and an `http://` URL would send
/// credentials in cleartext. Development keeps the platform loopback defaults
/// so `flutter run` works with no flags.
///
/// Exposed separately from the getter so the release contract is testable
/// without a release-mode compile.
String resolveApiBaseUrl({
  required String configured,
  required bool release,
  String developmentDefault = 'http://localhost:8000',
}) {
  final value = configured.trim();
  if (value.isEmpty) {
    if (release) {
      throw StateError(
        'API_BASE_URL must be provided for a release build. Rebuild with '
        '--dart-define=API_BASE_URL=https://<your-api-host>.',
      );
    }
    return developmentDefault;
  }
  final uri = Uri.tryParse(value);
  if (uri == null || uri.host.isEmpty) {
    throw StateError('API_BASE_URL must be an absolute http(s) URL.');
  }
  if (uri.scheme != 'http' && uri.scheme != 'https') {
    throw StateError('API_BASE_URL must use http or https.');
  }
  if (release && uri.scheme != 'https') {
    throw StateError(
      'A release build requires an https:// API_BASE_URL. Terminate TLS at '
      'your proxy or load balancer and pass that public URL.',
    );
  }
  if (release && _isNonPublicHost(uri.host)) {
    throw StateError(
      'A release build must not target a loopback or private address. Pass '
      'the public https:// API_BASE_URL.',
    );
  }
  return value.endsWith('/') ? value.substring(0, value.length - 1) : value;
}

bool _isNonPublicHost(String host) {
  final normalized = host.toLowerCase();
  if (normalized == 'localhost' ||
      normalized == '127.0.0.1' ||
      normalized == '::1' ||
      normalized == '10.0.2.2' ||
      normalized.endsWith('.local')) {
    return true;
  }
  if (normalized.startsWith('10.') || normalized.startsWith('192.168.')) {
    return true;
  }
  return RegExp(r'^172\.(1[6-9]|2\d|3[01])\.').hasMatch(normalized);
}
